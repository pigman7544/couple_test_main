def block(title,text):
    return f'◆ **{title}**\n{text}'

def particle(word,consonant,vowel):
    return consonant if (ord(word[-1])-0xAC00)%28 else vowel

def basis(label,x):
    month=x['anchors']['month']; day=x['anchors']['day']
    s=(f"{label}의 사주에서는 태어난 달의 자리인 월령에서 {x['season']}의 기운을 먼저 읽었어요. "
       f"여기에 담긴 {month}{particle(month,'은','는')} {GOD_MEANING[GROUP[month]]}에 비유할 수 있어요. ")
    if GROUP[day]==GROUP[month]:
        s+=f"가까운 관계를 비추는 일지의 {day}에서도 비슷한 결을 읽었어요."
    else:
        s+=f"가까운 관계를 비추는 일지의 {day}에서는 {GOD_MEANING[GROUP[day]]}도 보여요."
    if x['missing_hour']:
        s+=' 출생시간을 몰라 시간의 자리는 해석에서 뺐어요.'
    else:
        god=x['anchors']['hour']
        if GROUP[god]==GROUP[month]:
            s+=' 태어난 시간의 자리인 시주에서도 이 표현 방식이 이어져요.'
        else:
            s+=f" 태어난 시간의 자리인 시주에는 {GOD_MEANING[GROUP[god]]}도 담겨 있어요."
    if GROUP[month]!=x['theme']:
        s+=f" 다른 자리와 지장간을 함께 살폈을 때는 ‘{THEMES[x['theme']][0]}’{particle(THEMES[x['theme']][0],'이','가')} 두드러져, 이 이야기의 중심 실마리로 삼았어요."
    return s

