def select(actions, stem):
    """Try other scenes for the same role before falling back to the work."""
    for action in actions:
        for reading in action.readings:
            if stem in reading.stems:
                return action, reading
    return actions[0], None


def ordered_people(a, b):
    """Preserve the existing earth/metal and month-god role tie-break."""
    from story_report import count_elements, relationship_style

    def strength(person):
        counts = count_elements(person)
        god = relationship_style(person)['god']
        return counts['earth'] + counts['metal'] + (god in ('정관', '정재', '비견'))

    people = (('당신', a['day_pillar'][0]), ('상대방', b['day_pillar'][0]))
    return people if strength(a) >= strength(b) else people[::-1]


def profiles(cid, names, people):
    from story_report import STEM_NAME

    paragraphs = []
    for name, (label, stem), actions in zip(names, people, CHARACTERS[cid], strict=True):
        action, reading = select(actions, stem)
        paragraphs.append(f'◆ **{label}에게 비춰 보는 {name}**\n{action.event} {action.meaning}')
        if reading:
            paragraphs.append(
                f'명리에서는 {label}의 일간 **{STEM_NAME[stem]}({stem})**에서 '
                f'이와 닮은 모습인 **{reading.trait}**을 읽어요. {reading.reflection}'
            )
    return '\n\n'.join(paragraphs)
