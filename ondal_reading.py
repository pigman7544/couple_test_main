def enrich(result, a, b, rel, couple):
    (left, left_stem), (right, right_stem) = ordered_people(a, b)
    revise(result, left, right, {'stem': left_stem}, {'stem': right_stem}, rel['vector'])
    result['tagline'] = '서로 시작할 수 있도록 돕는 사이'
    result['questions'] = ['상대가 무언가 시작하려 할 때 어떤 도움부터 물어보면 좋을까요?']
    result['ending'] = result['questions'][0]
    result['sections'] = ['roles', 'story', 'saju_a', 'crisis', 'tip']
    result['chapters'] = [dict(key=key, title=title) for key, title in zip(result['sections'], (
        '온달이 맡은 일과 평강이 마련한 조건',
        '온달과 평강은 어떻게 함께 살게 됐을까요?',
        '도움을 주고받으며 각자의 일을 하는 법',
        '도움이 결정으로 앞서갈 때',
        '어디까지 함께할지 물어봐요',
    ))]
    return result


